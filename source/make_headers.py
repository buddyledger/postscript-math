"""Builds the dvips headers in dvips/ from the library's .ps files.

Each part of the library becomes its own header, so a document loads only the
parts it uses. A header is its .ps file with the DSC lines (%! and %%), which
must not appear inside a dvips header, and the other comment lines and blank
lines removed. All headers define their names in tx@NumericDict.
dvips/pst-numeric.pro, the TeX interface's own header, is not generated.

Do not edit the headers by hand: change the .ps file and run this again.

    python source/make_headers.py
"""
from pathlib import Path

PREFIX = "pst-numeric"
# part name, source file, parts it needs (load those headers first)
PARTS = [
    ("bignum", "bignumlibrary.ps", []),
    ("trig", "Trig.ps", []),
    ("matrix", "Matrix.ps", ["bignum (only for bignum matrices)"]),
    ("complex", "Complex.ps", ["matrix", "bignum (only for bignums)"]),
    ("calc", "Numeric.ps", ["matrix", "complex", "bignum (only for bignums)"]),
]

here = Path(__file__).resolve().parent      # source/
out_dir = here.parent / "dvips"
out_dir.mkdir(exist_ok=True)

for part, src, needs in PARTS:
    lines = (here / src).read_text(encoding="utf-8").splitlines()
    body = [l.rstrip() for l in lines
            if l.strip() and not l.lstrip().startswith("%")]
    head = [
        "%!",
        f"% {PREFIX}-{part}.pro: {src} of pst-numeric as a dvips header",
        "% Generated by make_headers.py, do not edit.",
        "% Copyright 2012, 2026 Buddy Ledger",
        "% LaTeX Project Public License 1.3c or later, see LICENSE",
        "% https://github.com/buddyledger/pst-numeric",
    ]
    if needs:
        head.append("% Needs: " + ", ".join(needs))
    text = "\n".join(head + body) + "\n"
    out = out_dir / f"{PREFIX}-{part}.pro"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(here.parent).as_posix()} ({len(text.encode())} bytes)")
